"use strict";
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const {fileURLToPath} = require('node:url');
const {randomUUID} = require('node:crypto');
const MAX_CONFIG_BYTES = 64 * 1024;
const record = value => value !== null && typeof value === 'object' && !Array.isArray(value);

function configurationPath(explicit, env = process.env) {
  const selected = explicit || env.REVISION_REQUEST_MCP_CONFIG || path.join(os.homedir(), '.revision-request', 'mcp.json');
  if (!path.isAbsolute(selected)) throw new Error('The connection file path must be absolute.');
  return path.resolve(selected);
}
function parseConfiguration(text) {
  if (Buffer.byteLength(text, 'utf8') > MAX_CONFIG_BYTES) throw new Error('The connection JSON exceeds 64 KiB.');
  let value;
  try { value = JSON.parse(text.replace(/^\uFEFF/, '')); }
  catch { throw new Error('Paste the Generic JSON from Revision Request: Copy MCP Configuration.'); }
  const entry = record(value) && record(value.mcpServers) && value.mcpServers.revision_request;
  if (!record(entry) || typeof entry.command !== 'string' || !path.isAbsolute(entry.command) ||
      !Array.isArray(entry.args) || !entry.args.every(item => typeof item === 'string' && !item.includes('\0'))) {
    throw new Error('Use the generated mcpServers.revision_request entry with an absolute command and arguments.');
  }
  if (!record(entry.env) || entry.env.ELECTRON_RUN_AS_NODE !== '1' || Object.keys(entry.env).length !== 1) {
    throw new Error('Keep the generated ELECTRON_RUN_AS_NODE=1 environment setting.');
  }
  const args = entry.args;
  if ((args.length !== 5 && args.length !== 7) || !path.isAbsolute(args[0]) ||
      !['rr-mcp.cjs', 'mcp-server.cjs'].includes(path.basename(args[0])) ||
      args[1] !== '--registry-dir' || !path.isAbsolute(args[2]) || args[3] !== '--workspace' ||
      (args.length === 7 && (args[5] !== '--instance-id' || !/^[a-f0-9-]{36}$/i.test(args[6])))) {
    throw new Error('Keep the adapter, registry directory, and explicit workspace arguments generated by VS Code.');
  }
  let workspace;
  try {
    const uri = new URL(args[4]);
    if (uri.protocol !== 'file:' || uri.search || uri.hash) throw new Error();
    workspace = fileURLToPath(uri);
    if (!path.isAbsolute(workspace)) throw new Error();
  } catch { throw new Error('The configured workspace must be an absolute local file URI.'); }
  // Store only the supported generated entry, never unrelated client settings.
  return {command: entry.command, args: [...args], env: {ELECTRON_RUN_AS_NODE: '1'}, workspace};
}
async function validatePaths(entry) {
  for (const [name, label, directory] of [
    [entry.command, 'VS Code runtime', false], [entry.args[0], 'Revision Request MCP adapter', false],
    [entry.workspace, 'Configured workspace', true],
  ]) {
    const info = await fs.stat(name).catch(() => undefined);
    if (!info || (directory ? !info.isDirectory() : !info.isFile())) {
      throw new Error(label + ' is unavailable. Open the workspace with Revision Request enabled and copy its MCP configuration again.');
    }
  }
}
async function readConfiguration(filename) {
  const info = await fs.stat(filename).catch(() => undefined);
  if (!info) throw new Error('Revision Request is not configured. Run the plugin setup skill or configure.cjs with the Generic JSON copied from VS Code.');
  if (!info.isFile() || info.size > MAX_CONFIG_BYTES) throw new Error('Use a regular connection JSON file no larger than 64 KiB.');
  const entry = parseConfiguration(await fs.readFile(filename, 'utf8'));
  await validatePaths(entry);
  return entry;
}
async function saveConfiguration(text, filename, replace = false) {
  const entry = parseConfiguration(text);
  await validatePaths(entry);
  const serialized = JSON.stringify({mcpServers: {revision_request: {
    command: entry.command, args: entry.args, env: entry.env,
  }}}, null, 2) + '\n';
  await fs.mkdir(path.dirname(filename), {recursive: true, mode: 0o700});
  if (!replace) {
    try { await fs.writeFile(filename, serialized, {flag: 'wx', mode: 0o600}); }
    catch (error) {
      if (error.code === 'EEXIST') throw new Error('A connection is already configured. Use --replace only to select the intended replacement workspace.');
      throw error;
    }
  } else {
    const previous = await fs.lstat(filename).catch(error => {if (error.code !== 'ENOENT') throw error;});
    if (previous && (!previous.isFile() || previous.isSymbolicLink())) throw new Error('Replace only a regular connection JSON file.');
    const temporary = filename + '.' + randomUUID() + '.tmp';
    try {
      await fs.writeFile(temporary, serialized, {flag: 'wx', mode: 0o600});
      await fs.rename(temporary, filename);
    } finally { await fs.unlink(temporary).catch(error => {if (error.code !== 'ENOENT') throw error;}); }
  }
  return entry;
}
module.exports = {MAX_CONFIG_BYTES, configurationPath, parseConfiguration, validatePaths, readConfiguration, saveConfiguration};
